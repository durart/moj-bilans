import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
await import('./ui/water.js');
const elements = Object.fromEntries(['#waterTotal','#waterGoalText','#waterBar','#waterCount','#undoWater'].map(id => [id, { textContent:'',style:{},disabled:false }]));
const select = id => { assert.ok(elements[id]); return elements[id]; };
const render = globalThis.MojBilansWaterUI.render;
render({ water:[{date:'2026-11-22',ml:250},{date:'2026-11-22',ml:300},{date:'2026-11-21',ml:500}],selectedDate:'2026-11-22',goals:{water:2000} },select,String,(a,b)=>Math.round(a/b*100));
assert.equal(elements['#waterTotal'].textContent,'550 ml');
assert.equal(elements['#waterGoalText'].textContent,'2000');
assert.equal(elements['#waterBar'].style.width,'28%');
assert.equal(elements['#waterCount'].textContent,'2 wpisów');
assert.equal(elements['#undoWater'].disabled,false);
render({ water:[],selectedDate:'2026-11-22',goals:{} },select,String,()=>0);
assert.equal(elements['#waterCount'].textContent,'0 wpisów');
assert.equal(elements['#undoWater'].disabled,true);
const html=readFileSync('index.html','utf8');
assert.ok(html.indexOf('ui/water.js?v=2.8.0') < html.indexOf('app.js?v=3.0.0'));
assert.match(readFileSync('sw.js','utf8'),/ui\/water\.js\?v=2\.8\.0/);
console.log('Water UI isolated rendering tests passed.');
