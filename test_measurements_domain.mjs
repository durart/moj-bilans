import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
await import('./domain/measurements.js');
const {sorted,value}=globalThis.MojBilansMeasurements;
const validDate = input => /^\d{4}-\d{2}-\d{2}$/.test(input);
const numeric = input => typeof input === 'number' && Number.isFinite(input);
const rows=[{date:'2026-11-22',waist:102},{date:'bad',waist:99},null,{date:'2026-11-20',waist:105}];
const result=sorted(rows,validDate);
assert.deepEqual(result.map(row=>row.date),['2026-11-20','2026-11-22']);
assert.equal(rows[0].date,'2026-11-22');
assert.equal(value(10,numeric),10);
assert.equal(value(300,numeric),300);
assert.equal(value(9,numeric),null);
assert.equal(value(301,numeric),null);
assert.equal(value(null,numeric),null);
assert.equal(value(101.5,numeric),101.5);
const html=readFileSync('index.html','utf8');
assert.ok(html.indexOf('domain/measurements.js?v=2.8.0') < html.indexOf('app.js?v=2.7.1'));
assert.match(readFileSync('sw.js','utf8'),/domain\/measurements\.js\?v=2\.8\.0/);
console.log('Measurements module compatibility tests passed.');
