import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
await import('./ui/settings.js');
const fields = new Map();
const select = id => { if (!fields.has(id)) fields.set(id, { value:null }); return fields.get(id); };
let context;
const ui = { setContext(value) { context=value; } };
const state={ goals:{kcal:2300,protein:150,carbs:220,fat:70,water:2500}, weights:[{date:'2026-11-20',kg:100},{date:'2026-11-22',kg:99},{date:'invalid',kg:88}] };
const validDate = date => /^\d{4}-\d{2}-\d{2}$/.test(date);
const numeric = value => typeof value === 'number' && Number.isFinite(value);
globalThis.MojBilansSettingsUI.render(state,select,key=>'#goal-'+key,validDate,numeric,ui);
for(const [key,value] of Object.entries(state.goals))assert.equal(fields.get('#goal-'+key).value,value);
assert.deepEqual(context.latestWeight,{date:'2026-11-22',kg:99});
assert.strictEqual(context.goals,state.goals);
globalThis.MojBilansSettingsUI.render({...state,weights:[]},select,key=>'#goal-'+key,validDate,numeric,ui);
assert.equal(context.latestWeight,null);
const html=readFileSync('index.html','utf8');
assert.ok(html.indexOf('ui/settings.js?v=2.8.0') < html.indexOf('app.js?v=3.1.0'));
assert.match(readFileSync('sw.js','utf8'),/ui\/settings\.js\?v=2\.8\.0/);
console.log('Settings UI module tests passed.');
