import assert from 'node:assert/strict';
import fs from 'node:fs';
const read=p=>fs.readFileSync(p,'utf8');
const app=read('app.js'),html=read('index.html'),sw=read('sw.js'),update=read('pwa-updater.js');
const manifest=JSON.parse(read('manifest.webmanifest'));
const check=(ok,message)=>assert.ok(ok,message);
check(app.includes("const KEY = 'moj-bilans-v1'"),'legacy production localStorage must remain');
check(app.includes("const LOCAL_COPIES_DB = 'moj-bilans-kopie-lokalne-v1'"),'legacy IndexedDB must remain');
assert.doesNotMatch(app,/moj-bilans-np21-v1|moj-bilans-np21-kopie-v1/);
check(app.includes('let storageFault'), 'corrupt state guard');
check(app.includes('if (!storageFault && localStorage.getItem(KEY)) queueAutomaticLocalCopy()'),'guard automatic backup');
check(app.includes('readback.json !== record.json'), 'verify IndexedDB saved backup');
check(app.includes('async function verifyLatestBackup()'), 'backup integrity check');
check(app.includes('if (localStorage.getItem(KEY) !== json)'), 'verify localStorage read-after-write');
check(html.includes('id="np21SaveStatus"'), 'save status');
check(html.includes('id="np21BackupHealth"'),'backup health');
check(html.includes('id="np21VerifyBackup"'),'integrity action');
check(html.includes('id="np21UpdateStatus"'),'PWA status');
check(html.includes('src="./pwa-updater.js?v=pfs2.3.0"'),'versioned updater');
check(sw.includes("'./pwa-updater.js?v=pfs2.3.0'"),'offline updater');
check(sw.includes("'./app.js?v=bp2.5.0'"),'offline app');
check(sw.includes("'./interfejs-wyszukiwarki.mjs?v=np2.1.1'"),'offline search');
check(sw.includes("k.startsWith('moj-bilans-cache-')"),'root SW removes its own previous caches');
check(!sw.includes("k.startsWith('moj-bilans-np21-cache-')"),'no test cache cleanup');
check(sw.includes("moj-bilans-cache-insights-body-v25"),'new production cache');
check(update.includes("registration.update()"),'manual update');
check(!update.includes("setInterval("),'no update polling');
check(!update.includes("TEST"),'no test labels');
check(!html.includes("WERSJA TESTOWA"),'no test banner');
check(manifest.id==='.'+'/'&&manifest.scope==='.'+'/'&&manifest.start_url==='.'+'/', 'same PWA identity');
check(manifest.icons.every(i=>i.src.startsWith('./icons/')),'root icons');
check(read('wyszukiwarka.mjs').includes('moj-bilans:off-search-cache:v1'),'search storage unchanged');
check(read('katalog-produktow.mjs').includes('moj-bilans:off-food-catalog:v1'),'catalog storage unchanged');
check(read('katalog-produktow.mjs').includes('moj-bilans:biedronka-off:v1'),'historical catalog key unchanged');
console.log('PASS v2.1 production integrity, backups, cache, versioned assets and data namespaces');
