import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const win={};
vm.runInNewContext(fs.readFileSync('historia-statystyki.js','utf8'),{window:win,Date});
vm.runInNewContext(fs.readFileSync('np-analytics-v24.js','utf8'),{window:win,Date});
const history=win.MojBilansHistory,analytics=win.MojBilansAnalytics24;
const goals={kcal:2300,protein:160,fat:75,carbs:240};
const day=(date,kcal,protein=100,fat=50,carbs=200)=>({id:date,date,grams:100,nutrients:{kcal,protein,fat,carbs}});
const entries=[day('2026-11-19',2300),day('2026-11-20',2200),day('2026-11-21',2400)];
const sum=history.historySummary(entries,'2026-11-15','2026-11-21');
const report=analytics.compute(sum,goals,'2026-11-21');
assert.equal(report.logged,3);
assert.equal(report.rangeDays,7);
assert.equal(report.inBand,3);
assert.equal(report.ratios.kcal,100);
assert.equal(report.compare.kcal.delta,200);
assert.equal(report.compare.protein.delta,0);
assert.equal(report.coverage,3/7);
assert.match(report.insight,/większości|połowie/i);
const missing=analytics.compute(history.historySummary([entries[1]],'2026-11-15','2026-11-21'),goals,'2026-11-21');
assert.equal(missing.compare.kcal,null);
assert.equal(missing.logged,1);
assert.equal(missing.ratios.kcal,96);
const none=analytics.compute(history.historySummary([],'2026-11-15','2026-11-21'),goals,'2026-11-21');
assert.equal(none.ratios.kcal,null);
assert.equal(none.compare.kcal,null);
assert.equal(none.inBand,0);
const partial=history.historySummary([{date:'2026-11-20',grams:100,nutrients:{kcal:2300,protein:null,fat:40,carbs:100}}],'2026-11-20','2026-11-20');
assert.match(analytics.compute(partial,goals,'2026-11-21').insight,/nie ma kompletnych/i);
assert.equal(history.periodRange('30d',new Date(2026,10,21,12)).from,'2026-10-23');
assert.equal(history.dateCount('2026-10-23','2026-11-21'),30);
assert.equal(analytics.dayBefore('2026-11-01'),'2026-10-31');
console.log('PASS History 2.4: exact 30d, missing days, goal band, averages, comparisons, incomplete macro and calendar rollover');
