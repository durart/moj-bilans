import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
await import('./domain/diary-state.js');
const { initialize } = globalThis.MojBilansDiaryState;
const defaults = { kcal: 2300, protein: 160 };
const today = () => '2026-11-22';
const numeric = value => Number.isFinite(Number(value)) && value !== null && value !== '';
const original = { goals: { kcal: 2200 }, entries: [{ id: 'saved' }], recipes: [{ id: 'recipe' }], weightGoal: 91, portions: { a: 100 } };
const state = initialize(original, defaults, today, numeric);
assert.deepEqual(state.goals, { kcal: 2200, protein: 160 });
assert.strictEqual(state.entries, original.entries);
assert.strictEqual(state.recipes, original.recipes);
assert.strictEqual(state.portions, original.portions);
assert.equal(state.weightGoal, 91);
assert.equal(state.selectedDate, '2026-11-22');
assert.equal(initialize({ weightGoal: 1000, entries: {} }, defaults, today, numeric).weightGoal, 90);
assert.deepEqual(initialize({ entries: {} }, defaults, today, numeric).entries, []);
const html = readFileSync('index.html', 'utf8');
assert.ok(html.indexOf('domain/diary-state.js?v=2.8.0') < html.indexOf('app.js?v=3.0.0'));
assert.match(readFileSync('sw.js', 'utf8'), /domain\/diary-state\.js\?v=2\.8\.0/);
console.log('Diary initializer compatibility and offline registration verified.');
